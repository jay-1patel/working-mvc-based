class NormalizePathMiddleware:
    """Strip accidental whitespace from the request path (common Postman typo)."""

    def __init__(self, app):
        self.app = app

    async def __call__(self, scope, receive, send):
        if scope["type"] in ("http", "websocket"):
            path = scope.get("path") or ""
            cleaned = path.strip()
            if cleaned != path:
                scope = dict(scope)
                scope["path"] = cleaned
                if "raw_path" in scope:
                    scope["raw_path"] = cleaned.encode("utf-8", "ignore")
        await self.app(scope, receive, send)


_PUBLIC_API_ROUTES = (
    re.compile(r"^/api/auth/(?:login|status|signup)$"),
    # Uploaded media is intentionally public: Send2Digital/WhatsApp fetches
    # these URLs without an admin session. Filenames are generated by the
    # backend and the static mounts expose only the configured upload folders.
    re.compile(r"^/api/(?:logos|uploads/(?:chat|product_images|brochures))(?:/.*)?$"),
    re.compile(r"^/api/webhooks/payments/[^/]+/[^/]+$"),
    re.compile(r"^/api/tenants(?:/[^/]+)?/google-connect/callback$"),
)
_TENANT_TOKEN_ROUTES = (
    re.compile(r"^/api/admin/tenants/[^/]+(?:/|$)"),
    re.compile(r"^/api/tenants/[^/]+(?:/|$)"),
)


async def _load_body_credentials(request: Request) -> None:
    """Pull username + session_id from JSON/form body into request.state."""
    content_type = (request.headers.get("content-type") or "").lower()
    try:
        body_bytes = await request.body()
    except Exception:
        return

    async def receive():
        return {"type": "http.request", "body": body_bytes, "more_body": False}

    request._receive = receive

    username = ""
    session_id = ""

    def _from_mapping(payload: dict) -> None:
        nonlocal username, session_id
        username = username or str(payload.get("username") or "").strip()
        session_id = session_id or str(payload.get("session_id") or "").strip()

    if body_bytes and "application/json" in content_type:
        try:
            payload = json.loads(body_bytes)
        except Exception:
            payload = None
        if isinstance(payload, dict):
            _from_mapping(payload)
    elif body_bytes and (
        "application/x-www-form-urlencoded" in content_type or "multipart/form-data" in content_type
    ):
        form = await request.form()
        username = str(form.get("username") or "").strip()
        session_id = str(form.get("session_id") or "").strip()
        # Re-inject raw body so downstream can still parse multipart/form.
        async def receive_again():
            return {"type": "http.request", "body": body_bytes, "more_body": False}

        request._receive = receive_again

    # Robust fallback: if body_bytes is present and credentials not yet
    # resolved, attempt JSON decode (e.g. curl -d without explicit Content-Type).
    if body_bytes and not (session_id and username):
        try:
            payload = json.loads(body_bytes)
            if isinstance(payload, dict):
                _from_mapping(payload)
        except Exception:
            pass

    if username:
        request.state.auth_username = username
    if session_id:
        request.state.auth_session_id = session_id


async def admin_session_auth_middleware(request: Request, call_next):
    """Require a live admin session on every protected /api request.

    Credentials: headers or JSON/form fields ``username`` + ``session_id`` only.
    No Authorization header is required.
    """
    path = request.url.path
    if request.method == "OPTIONS" or not path.startswith("/api/"):
        return await call_next(request)
    if any(pattern.fullmatch(path) for pattern in _PUBLIC_API_ROUTES):
        return await call_next(request)
    auth_header = request.headers.get("authorization", "")
    if auth_header.lower().startswith("bearer ") and any(
        pattern.match(path) for pattern in _TENANT_TOKEN_ROUTES
    ):
        return await call_next(request)
    header_username = str(request.headers.get("username") or "").strip()
    header_session = str(request.headers.get("session_id") or "").strip()
    if header_username:
        request.state.auth_username = header_username
    if header_session:
        request.state.auth_session_id = header_session
    if request.method in {"POST", "PUT", "PATCH", "DELETE"} and not (
        header_session and header_username
    ):
        await _load_body_credentials(request)
    try:
        try:
            from routes.auth import authenticate_basic_header
        except ImportError:
            from backend.routes.auth import authenticate_basic_header
        authenticate_basic_header(request)
    except StarletteHTTPException as exc:
        request.state.api_code = exc.status_code
        return json_fail(
            exc.detail,
            exc.status_code,
            headers=getattr(exc, "headers", None),
        )
    return await call_next(request)


async def super_admin_view_only_middleware(request: Request, call_next):
    """Refuse tenant-data writes by a super-admin principal (decided rule).

    The dependency-level guard in routes/auth.py covers every route that
    passes through ``require_tenant_access`` / ``require_permission``. This
    middleware is the same rule for the routers that authenticate ad hoc
    (legacy global surfaces, callbacks, inbox, complaints, orders, catalog):
    for a non-GET request carrying an admin JWT, resolve the caller's role
    and refuse tenant-data writes when the caller is a super admin. Tenant
    API tokens are not JWTs and are unaffected; unauthenticated and
    non-super requests pass straight through to the route's own checks.
    """
    if request.method not in ("POST", "PUT", "PATCH", "DELETE"):
        return await call_next(request)
    try:
        from routes.auth import is_tenant_data_write
    except ImportError:
        from backend.routes.auth import is_tenant_data_write
    if not is_tenant_data_write(request.method, request.url.path):
        return await call_next(request)
    role = (getattr(request.state, "current_admin", None) or {}).get("role")
    if role == "super_admin":
        request.state.api_code = 403
        return json_fail(
            (
                "Super admins are view-only inside tenants: this change must "
                "come from the tenant's admin (and is approved by you)."
            ),
            403,
            api=f"{request.method} {request.url.path}",
            error="super_admin_view_only",
        )
    return await call_next(request)


async def audit_request_context(request: Request, call_next):
    """Provide trusted network metadata to audit writes for this request."""
    peer = request.client.host if request.client else None
    ip = trusted_client_ip(peer, request.headers.get("x-forwarded-for"))
    set_audit_request_context(ip_address=ip, user_agent=request.headers.get("user-agent"))
    try:
        return await call_next(request)
    finally:
        clear_audit_request_context()


async def audit_mutations_middleware(request: Request, call_next):
    try:
        from routes.auth import is_read_only_post
    except ImportError:
        from backend.routes.auth import is_read_only_post
    if (
        request.method not in ("POST", "PUT", "PATCH", "DELETE")
        or not request.url.path.startswith("/api/admin")
        or is_read_only_post(request.method, request.url.path)
    ):
        return await call_next(request)

    content_type = request.headers.get("content-type", "")
    if "multipart/form-data" in content_type:
        body_content = "<multipart_file_upload>"
    else:
        try:
            body_bytes = await request.body()
            async def receive(): return {"type": "http.request", "body": body_bytes}
            request._receive = receive
            body_content = body_bytes.decode('utf-8')
            if "application/json" in content_type:
                body_content = json.loads(body_content)
        except Exception:
            body_content = "<unparseable>"

    response = await call_next(request)

    # Prefer logical API code (always-200 envelope) over transport status.
    logical = getattr(request.state, "api_code", None)
    if logical is None:
        logical = response.status_code
    if 200 <= int(logical) < 300 and getattr(request.state, "api_success", 1) != 0:
        actor_username = (getattr(request.state, "current_admin", None) or {}).get("username", "unknown")
        
        try:
            record_admin_audit_event(
                None,
                action=f"{request.method} {request.url.path}",
                actor={"username": actor_username},
                resource_type="api_endpoint",
                resource_id=request.url.path,
                details={"request_body": body_content, "query_params": dict(request.query_params)},
            )
        except Exception as e:
            logger.exception("AUDIT_MUTATION_RECORD_FAILED | %s %s", request.method, request.url.path)

    return response


# ── Phase 1: request-id, one REQ log line per request, central error handlers ──
# Every request gets a short id (req_<8 hex>). It is stored in a contextvar and
# on request.state, returned as the X-Request-Id header, included in every error
# response body, and printed in the app's own REQ log line — so any failure can be
# traced from the browser console line to exactly one backend log line / error row.


def get_request_id() -> str:
    return _request_id_var.get()


def _new_request_id() -> str:
    return "req_" + secrets.token_hex(4)


def _tenant_from_path(path: str):
    parts = [seg for seg in path.split("/") if seg]
    try:
        i = parts.index("tenants")
    except ValueError:
        return None
    return parts[i + 1] if i + 1 < len(parts) else None


def _request_id_for(request: Request) -> str:
    return getattr(request.state, "request_id", None) or _request_id_var.get() or _new_request_id()


async def request_id_middleware(request: Request, call_next):
    rid = _new_request_id()
    request.state.request_id = rid
    token = _request_id_var.set(rid)
    started = time.perf_counter()
    api = f"{request.method} {request.url.path}"
    tenant = _tenant_from_path(request.url.path)
    try:
        from routes.auth import BODY_TENANT_POST_PATHS
    except ImportError:
        from backend.routes.auth import BODY_TENANT_POST_PATHS
    if request.method == "POST" and request.url.path in BODY_TENANT_POST_PATHS:
        # Tenant comes from username/session_id auth — never from the JSON body.
        tenant = None
        try:
            try:
                from routes.auth import authenticate_basic_header
            except ImportError:
                from backend.routes.auth import authenticate_basic_header
            admin = authenticate_basic_header(request)
            tenant = str(admin.get("tenant_id") or "").strip() or None
            request.state.error_tenant_id = tenant
        except Exception:
            tenant = None
    api_token = request_api_var.set(api)
    tenant_token = error_tenant_var.set(tenant)
    context_token = error_context_var.set({'tenant_id': tenant})
    tenant_part = f" | tenant={tenant}" if tenant else ""
    try:
        try:
            response = await call_next(request)
        except Exception as exc:
            # Handle while context is still alive so service and API events
            # retain the same request ID. No second report from the outer app.
            response = await unhandled_exception_handler(request, exc)
        logical = getattr(request.state, "api_code", None)
        if logical is None:
            logical = response.status_code
        if int(logical) >= 400 and not getattr(request.state, 'error_recorded', False):
            from services.error_reporter import report_error
            report_error(
                'api', api,
                getattr(request.state, 'error_message', None) or f'HTTP {logical}',
                tenant_id=getattr(request.state, 'error_tenant_id', tenant),
                request_id=rid, http_status=int(logical),
                detail=getattr(request.state, 'error_detail', ''),
                severity='error' if int(logical) >= 500 else 'warning',
                notify=False,
            )
            request.state.error_recorded = True
    finally:
        _request_id_var.reset(token)
        request_api_var.reset(api_token)
        error_tenant_var.reset(tenant_token)
        error_context_var.reset(context_token)
    ms = int((time.perf_counter() - started) * 1000)
    logical = getattr(request.state, "api_code", None)
    if logical is None:
        logical = response.status_code
    line = f"REQ {rid} | {api} → {response.status_code} (code={logical}) | {ms}ms{tenant_part}"
    if int(logical) >= 500:
        logger.error(line)
    else:
        logger.info(line)
    response.headers["X-Request-Id"] = rid
    response.headers["X-Api-Code"] = str(logical)
    return response


async def http_exception_handler(request: Request, exc: StarletteHTTPException):
    """Always HTTP 200; failure is ``success: 0`` + logical ``code`` in the body."""
    rid = _request_id_for(request)
    api = f"{request.method} {request.url.path}"
    detail = exc.detail
    request.state.api_code = exc.status_code
    request.state.api_success = 0
    request.state.error_message = detail if isinstance(detail, str) else f'HTTP {exc.status_code}'
    request.state.error_detail = json.dumps(detail, default=str) if not isinstance(detail, str) else detail
    headers = dict(exc.headers or {})
    headers["X-Request-Id"] = rid
    headers["X-Api-Code"] = str(exc.status_code)
    return json_fail(
        detail,
        exc.status_code,
        request_id=rid,
        api=api,
        headers=headers,
    )


async def validation_exception_handler(request: Request, exc: RequestValidationError):
    rid = _request_id_for(request)
    # Validation inputs can contain passwords/files. Persist only field names,
    # validation types and messages, never the submitted values or request body.
    errors = [{key: error[key] for key in ('loc', 'msg', 'type') if key in error}
              for error in exc.errors()]
    request.state.api_code = 422
    request.state.api_success = 0
    request.state.error_message = 'Request validation failed'
    request.state.error_detail = json.dumps(errors, default=str)
    return json_fail(
        jsonable_encoder(errors),
        422,
        request_id=rid,
        api=f'{request.method} {request.url.path}',
        error='Request validation failed',
        headers={'X-Request-Id': rid, 'X-Api-Code': '422'},
    )


async def unhandled_exception_handler(request: Request, exc: Exception):
    """One central handler for unhandled errors: JSON (never plain text), one
    clean ERROR line, and a durable row via the error reporter. The reporter is
    guarded — its failure can never break this response. Transport status is
    always 200; body carries success=0 and code=500."""
    rid = _request_id_for(request)
    api = f"{request.method} {request.url.path}"
    tenant = getattr(request.state, 'error_tenant_id', None) or _tenant_from_path(request.url.path)
    request.state.api_code = 500
    request.state.api_success = 0
    logger.error(
        f"API_FAIL | req={rid} | api={api} | tenant={tenant or '-'} "
        f"| {type(exc).__name__}: {str(exc)[:300]}"
    )
    logger.debug("Unhandled exception traceback for %s", rid, exc_info=exc)
    try:
        from services.error_reporter import report_error
        report_error(
            "api", api, exc,
            tenant_id=tenant, request_id=rid, http_status=500,
            detail="".join(_traceback.format_exception(type(exc), exc, exc.__traceback__))[-3500:],
        )
        request.state.error_recorded = True
    except Exception:
        logger.error(f"ERROR_REPORT_FAILED | req={rid} | api={api}", exc_info=True)
    return json_fail(
        "Internal Server Error",
        500,
        request_id=rid,
        api=api,
        headers={"X-Request-Id": rid, "X-Api-Code": "500"},
    )


async def api_success_envelope_middleware(request: Request, call_next):
    """Force JSON /api responses to HTTP 200 with a ``success`` 1/0 flag.

    Skips non-JSON bodies (files, streams, webhook plaintext challenges).
    """
    response = await call_next(request)
    path = request.url.path or ""
    if not path.startswith("/api/"):
        return response
    content_type = (response.headers.get("content-type") or "").lower()
    if "application/json" not in content_type:
        return response

    body_chunks: list[bytes] = []
    async for chunk in response.body_iterator:
        body_chunks.append(chunk if isinstance(chunk, (bytes, bytearray)) else bytes(chunk))
    raw = b"".join(body_chunks)

    transport_status = response.status_code
    logical = getattr(request.state, "api_code", None)
    if logical is None:
        logical = transport_status
    logical = int(logical)

    headers = {
        k: v
        for k, v in response.headers.items()
        if k.lower() not in ("content-length", "content-type")
    }

    try:
        payload = json.loads(raw.decode("utf-8")) if raw else {}
    except Exception:
        request.state.api_code = logical
        request.state.api_success = 0 if logical >= 400 else 1
        headers["X-Api-Code"] = str(logical)
        from starlette.responses import Response as StarletteResponse
        return StarletteResponse(
            content=raw,
            status_code=200,
            media_type=content_type or "application/json",
            headers=headers,
        )

    if not isinstance(payload, dict):
        if logical >= 400:
            payload = {
                "success": 0,
                "code": logical,
                "detail": payload,
                "error": f"HTTP {logical}",
            }
        else:
            payload = success_payload({"data": payload})
    else:
        ensure_success_flag(payload, logical_code=logical)

    if payload.get("success") == 0:
        request.state.api_success = 0
        fail_code = payload.get("code", logical if logical >= 400 else 400)
        request.state.api_code = int(fail_code)
        payload["code"] = request.state.api_code
    else:
        request.state.api_success = 1
        # Preserve original 2xx (201/202) for audit; never keep a 4xx/5xx on success.
        request.state.api_code = transport_status if transport_status < 400 else 200

    headers["X-Api-Code"] = str(request.state.api_code)
    return JSONResponse(status_code=200, content=payload, headers=headers)
